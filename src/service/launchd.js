// Manages the launchd user agent that keeps `vos serve` running in the
// background, so the board follows config.yaml across reboots and logouts
// without a terminal open.
//
// launchd rather than crontab: cron has no equivalent of KeepAlive, and macOS
// treats per-user cron as legacy. The agent supervises one long-lived `serve`
// process; the in-process node-cron scheduler still owns all timing, so
// config.yaml stays the single source of truth and no cron expression ever
// has to be translated into a StartCalendarInterval.

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadConfig } from '../config.js';
import { installWakeDaemon, uninstallWakeDaemon, wakesStatus } from './pmset-wakes.js';

export { installWakeDaemon, uninstallWakeDaemon };

const execFileAsync = promisify(execFile);

// Machine-agnostic on purpose: the same checkout can be installed on any Mac.
// Paths in the generated plist are captured from *this* process at install time
// (this machine's node binary, this checkout's directory, this user's home).
export const LABEL = 'local.vos';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ENTRY = join(ROOT, 'src', 'index.js');
const PLIST_PATH = join(homedir(), 'Library', 'LaunchAgents', `${LABEL}.plist`);
const LOG_DIR = join(ROOT, 'logs');

export const paths = { root: ROOT, plist: PLIST_PATH, logDir: LOG_DIR };

export const supported = process.platform === 'darwin';

function domainTarget() {
  return `gui/${process.getuid()}`;
}

function assertSupported() {
  if (!supported) {
    throw new Error(`Background service requires macOS (launchd); this is ${process.platform}.`);
  }
}

function xmlEscape(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;',
  }[c]));
}

function buildPlist(tz) {
  // caffeinate -i: no idle sleep (this Mac's Energy Saver is "sleep after 1
  // minute"). -s: no system sleep on AC. Lid-close on Apple Silicon still
  // sleeps; that is a hardware path caffeinate cannot block.
  const args = ['/usr/bin/caffeinate', '-i', '-s', process.execPath, ENTRY, 'serve'];
  const tzXml = tz
    ? `\t\t<key>TZ</key>\n\t\t<string>${xmlEscape(tz)}</string>\n`
    : '';
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
\t<key>Label</key>
\t<string>${xmlEscape(LABEL)}</string>

\t<!-- Generated by \`vos service install\` / \`restart\`. Edits here are
\t     overwritten; change config/config.yaml or .env instead. -->
\t<key>ProgramArguments</key>
\t<array>
${args.map((a) => `\t\t<string>${xmlEscape(a)}</string>`).join('\n')}
\t</array>

\t<!-- dotenv resolves .env against the working directory, so this has to stay
\t     the project root or the API key will not be found. -->
\t<key>WorkingDirectory</key>
\t<string>${xmlEscape(ROOT)}</string>

\t<key>EnvironmentVariables</key>
\t<dict>
\t\t<key>PATH</key>
\t\t<string>/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
${tzXml}\t</dict>

\t<key>RunAtLoad</key>
\t<true/>
\t<key>KeepAlive</key>
\t<true/>

\t<key>StandardOutPath</key>
\t<string>${xmlEscape(join(LOG_DIR, 'service.out.log'))}</string>
\t<key>StandardErrorPath</key>
\t<string>${xmlEscape(join(LOG_DIR, 'service.err.log'))}</string>
</dict>
</plist>
`;
}

async function launchctl(args) {
  try {
    const { stdout, stderr } = await execFileAsync('launchctl', args);
    return { ok: true, stdout, stderr };
  } catch (err) {
    return { ok: false, stdout: err.stdout || '', stderr: err.stderr || err.message, code: err.code };
  }
}

export async function status() {
  if (!supported) {
    return { supported: false, installed: false, running: false, pid: null, label: LABEL };
  }
  const installed = existsSync(PLIST_PATH);
  const res = await launchctl(['list', LABEL]);
  // `launchctl list <label>` exits non-zero when the job is not loaded. When it
  // is loaded but not currently running, the PID key is absent instead.
  const pidMatch = res.ok ? res.stdout.match(/"PID"\s*=\s*(\d+)/) : null;
  const pid = pidMatch ? Number(pidMatch[1]) : null;
  const wakes = await loadWakes();
  return {
    supported: true,
    installed,
    loaded: res.ok,
    running: pid !== null,
    pid,
    // True when the process answering this call *is* the supervised one, which
    // means disabling the service will terminate the server mid-request.
    isSelf: pid !== null && pid === process.pid,
    label: LABEL,
    plistPath: PLIST_PATH,
    logDir: LOG_DIR,
    wakes,
  };
}

async function loadWakes() {
  try {
    return await wakesStatus();
  } catch (err) {
    return { installed: false, error: err.message };
  }
}

export async function writePlist() {
  assertSupported();
  await mkdir(dirname(PLIST_PATH), { recursive: true });
  await mkdir(LOG_DIR, { recursive: true });
  const cfg = await loadConfig();
  await writeFile(PLIST_PATH, buildPlist(cfg.board?.timezone || ''), 'utf8');
  return PLIST_PATH;
}

// Rewrite the user-agent plist and bounce the process. No admin prompt —
// wakes are left alone. Use after git pull so caffeinate / catch-up take effect.
export async function restart() {
  assertSupported();
  await writePlist();
  return bootstrap();
}

async function sleep(ms) {
  await new Promise((r) => setTimeout(r, ms));
}

async function loadedPid() {
  const res = await launchctl(['list', LABEL]);
  if (!res.ok) return null;
  const m = res.stdout.match(/"PID"\s*=\s*(\d+)/);
  return m ? Number(m[1]) : null;
}

async function unloadAgent() {
  // Path form first: more reliable than label-only when KeepAlive is racing.
  await launchctl(['bootout', domainTarget(), PLIST_PATH]);
  await launchctl(['bootout', `${domainTarget()}/${LABEL}`]);
  // Deprecated but still the reliable way to drop a ~/Library/LaunchAgents job
  // from a non-Aqua context (Cursor terminal, SSH) where gui bootstrap fails.
  await launchctl(['unload', PLIST_PATH]);
  const deadline = Date.now() + 4000;
  while (Date.now() < deadline) {
    if (await loadedPid() === null) return;
    await sleep(150);
  }
}

export async function bootstrap() {
  assertSupported();
  await unloadAgent();
  await sleep(250);

  let res = await launchctl(['bootstrap', domainTarget(), PLIST_PATH]);
  if (!res.ok) {
    // 125: "Domain does not support specified action" — typical when this
    // process is not in an Aqua gui session (IDE terminal, SSH). load(1)
    // still registers a plist that lives in ~/Library/LaunchAgents.
    res = await launchctl(['load', '-w', PLIST_PATH]);
  }
  if (!res.ok) {
    const detail = (res.stderr || res.stdout || `exit ${res.code}`).trim();
    throw new Error(`launchctl failed to start ${LABEL}: ${detail}`);
  }
  return status();
}

export async function bootout() {
  assertSupported();
  const res = await launchctl(['bootout', `${domainTarget()}/${LABEL}`]);
  // "No such process" just means it was already stopped, which is the goal.
  if (!res.ok && !/no such process|not find/i.test(res.stderr)) {
    throw new Error(`launchctl bootout failed: ${res.stderr.trim() || `exit ${res.code}`}`);
  }
}

export async function install() {
  // Admin prompt first. If it is cancelled, do not leave a LaunchAgents plist
  // behind that macOS would auto-load at the next login.
  await installWakeDaemon();
  await writePlist();
  return bootstrap();
}

export async function uninstallAgent() {
  assertSupported();
  // Remove the plist *before* booting out. When the caller is the supervised
  // process, bootout terminates it mid-call, so anything after that line never
  // runs — and a leftover plist in ~/Library/LaunchAgents is auto-loaded at the
  // next login, quietly resurrecting a service the user just disabled.
  // bootout targets the loaded job by label, so the missing file is fine.
  await rm(PLIST_PATH, { force: true });
  await bootout();
}

export async function uninstall() {
  assertSupported();
  await uninstallWakeDaemon();
  await uninstallAgent();
  return status();
}
